// Package rpgo — клиент REST API Почты России ИС ЭПС / ЭЗП
// («Электронные заказные письма»): отправка писем, уведомления о вручении,
// статус и содержимое электронных уведомлений, коды/история доступа к
// письму, выгрузка реестра ф103.
//
// Продуктивный и интеграционный контуры доступны только по каналу,
// уже защищённому ГОСТ TLS или VipNet (см. документ «Памятка по
// подключению клиентов к ИС ЭПС», разделы 4-5) — rpgo говорит обычным
// HTTP(S)+Basic auth на тот baseURL, который ему дали, точно так же, как
// в примерах самой Почты России, где запросы идут на локальный
// stunnel/VipNet-эндпоинт (например, http://localhost:3080). Сам этот
// пакет ГОСТ TLS не реализует.
//
// Версия API — это сегмент URL-пути (например, "v2.6"), а не что-то
// согласуемое, и Почта России уже не раз её меняла. По умолчанию Client
// использует версию, подтверждённую по актуальной документации вендора,
// но перед использованием стоит сверить версию со своим договором/
// поддержкой и при необходимости переопределить её через WithAPIVersion.

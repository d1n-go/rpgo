package rpgo

import (
	"context"
	"io"
	"net/http"
	"time"
)

// GetF103Registry скачивает zip-архив реестра почтовых отправлений (форма
// 103) за указанную дату. Используются только компоненты год/месяц/день
// самого date — часовой пояс игнорируется, никакого пересчёта в
// московское время не делается. Реестр ключуется московской бизнес-датой,
// поэтому если date получен из time.Now() или другого "момента времени", а
// не заранее известной календарной даты, приведите его к московской зоне
// сами (date.In(loc)) перед вызовом — иначе, например, вызов около полуночи
// по Москве, но не по Москве живущим сервисом, тихо запросит не тот день.
// Почта России хранит реестры только за последние 30 дней.
//
// Закрыть возвращённый reader — обязанность вызывающего кода. Чтение из
// него привязано к ctx запроса: если ctx будет отменён раньше, чем тело
// будет полностью прочитано и закрыто, последующие Read вернут ошибку
// отменённого контекста.
func (c *Client) GetF103Registry(ctx context.Context, date time.Time) (io.ReadCloser, error) {
	req, err := c.newRequest(ctx, http.MethodGet, c.pathf("/f103", date.Format("20060102"), ""), nil)
	if err != nil {
		return nil, err
	}
	resp, err := c.doRaw(req)
	if err != nil {
		return nil, err
	}
	return resp.Body, nil
}
